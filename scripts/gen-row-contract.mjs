// Generates the row contract from the data team's table definition
// (contract/india_bus_wrap_2026.table.json), so it is never hand-maintained:
//
//   server/wrap/pipelineColumns.mjs   column names, JSON types, nullability (used by the adapter)
//   contract/openapi.yaml             the PipelineRow schema block (between the two marker comments)
//
// Run after the table changes:  npm run gen:contract
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dummyRow } from '../server/data/dummyRows.mjs';

const root = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const table = JSON.parse(await readFile(root('contract/india_bus_wrap_2026.table.json'), 'utf8'));

// Columns the source query can leave NULL (LEFT JOINs, NULLIF/IF without else, MIN/MAX over all-null values).
const NULLABLE = new Set([
  'trips_change_pct', 'longest_gap_days', 'trips_percentile', 'rarest_destination', 'top_route_rank',
  'top_route_src_lat', 'top_route_src_lon', 'top_route_dst_lat', 'top_route_dst_lon',
  'fav_boarding_point_id', 'fav_dropping_point_id', 'avg_lead_days', 'closest_booking_minutes', 'top_seat',
  'fav_operator', 'savings_equivalent_tickets', 'best_deal_inr', 'best_deal_route', 'cheapest_ticket_inr',
]);
const JSON_TYPE = { BIGINT: 'integer', DOUBLE: 'number', STRING: 'string', DATE: 'string' };

const columns = table.schema.map((c) => ({ name: c.name, sql: c.type, json: JSON_TYPE[c.type], nullable: NULLABLE.has(c.name), description: c.description }));
const unknown = columns.filter((c) => !c.json);
if (unknown.length) throw new Error(`Unmapped SQL types: ${unknown.map((c) => `${c.name}:${c.sql}`).join(', ')}`);

// 1. Column types for the adapter
await writeFile(root('server/wrap/pipelineColumns.mjs'), `// GENERATED by scripts/gen-row-contract.mjs from contract/india_bus_wrap_2026.table.json. Do not edit.
// One entry per column of ${table.also_served_as}: JSON type as served by GET /wrap/{rb_user_id}, and whether it can be null.

export const TABLE = ${JSON.stringify(table.also_served_as)};
export const COLUMN_TYPES = {
${columns.map((c) => `  ${c.name}: { type: '${c.json}', nullable: ${c.nullable} },`).join('\n')}
};
export const COLUMNS = Object.keys(COLUMN_TYPES);
`);

// 2. PipelineRow block in the OpenAPI spec
const q = (s) => JSON.stringify(s); // JSON strings are valid YAML scalars
const example = dummyRow(42);
const prop = (c) => {
  const fmt = c.sql === 'BIGINT' ? ', format: int64' : c.sql === 'DATE' ? ', format: date-time' : '';
  const desc = `${c.sql}. ${c.description}${c.sql === 'DATE' ? ' Served as an ISO date-time at midnight UTC, e.g. 2026-02-25T00:00:00Z.' : ''}`;
  return `        ${c.name}: { type: ${c.json}${fmt}${c.nullable ? ', nullable: true' : ''}, description: ${q(desc)} }`;
};
const block = [
  '    # ---- Pipeline input: GENERATED by scripts/gen-row-contract.mjs, do not edit by hand ----',
  '    PipelineRow:',
  '      type: object',
  '      description: |',
  `        One row of ${table.also_served_as} (${table.table}), as returned by the data`,
  '        serving API: GET {WRAP_DATA_API_URL}/wrap/{rb_user_id} with a bearer token. The wrap',
  '        server fetches it server-side, adapts it (server/wrap/facts.mjs) and composes the',
  '        WrapResponse the apps render. Not returned by POST /api/v1/wrap.',
  `        ${table.description.replace(/\n/g, ' ')}`,
  '        Extra columns the table adds later are allowed and ignored until the adapter uses them.',
  `      required: [${columns.map((c) => c.name).join(', ')}]`,
  '      properties:',
  ...columns.map(prop),
  '      example:',
  ...columns.map((c) => `        ${c.name}: ${example[c.name] === null ? 'null' : typeof example[c.name] === 'string' ? q(example[c.name]) : example[c.name]}`),
  '    # ---- end of generated PipelineRow ----',
].join('\n');

const specPath = root('contract/openapi.yaml');
const spec = await readFile(specPath, 'utf8');
const start = spec.search(/^ {4}# ---- Pipeline input.*$/m);
const endMarker = spec.indexOf('    # ---- end of generated PipelineRow ----');
const pageMarker = spec.indexOf('    # ---- Page payloads');
if (start < 0 || pageMarker < 0) throw new Error('openapi.yaml markers not found');
const end = endMarker > 0 ? endMarker + '    # ---- end of generated PipelineRow ----'.length : pageMarker;
await writeFile(specPath, `${spec.slice(0, start)}${block}\n\n${spec.slice(end).replace(/^\n+/, '')}`);
console.log(`PipelineRow: ${columns.length} columns (${columns.filter((c) => c.nullable).length} nullable) → openapi.yaml, server/wrap/pipelineColumns.mjs`);
